"""
SEO router (ECO.NOVA) — centralized, production-grade SEO surfaces.

Everything is generated by the backend/app/seo/ engine package so the site
stays consistent and free of legacy BiBi Cars artifacts:

  GET /api/seo/robots.txt            env-aware robots
  GET /api/seo/sitemap.xml           sitemap INDEX
  GET /api/seo/sitemap-pages.xml     static public pages (+hreflang)
  GET /api/seo/sitemap-catalog.xml   waste categories + codes
  GET /api/seo/sitemap-blog.xml      published articles
  GET /api/seo/sitemap-images.xml    image sitemap
  GET /api/seo/meta                  per-route metadata + JSON-LD (frontend)
  GET /api/seo/runtime-config        public analytics/verification config
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

